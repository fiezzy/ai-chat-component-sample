import path from 'node:path'

/** `arrow-down.svg` becomes the `ArrowDownIcon` component. */
const toIconName = (componentName) => `${componentName.replace(/^Svg/, '')}Icon`

/** @type {import('@svgr/core').Config} */
const config = {
  typescript: true,
  jsxRuntime: 'automatic',
  // Icons take their size from CSS, so the generated SVG has none of its own.
  dimensions: false,
  svgProps: { 'aria-hidden': 'true' },
  // The project's Prettier and ESLint format the output, see `pnpm icons`.
  prettier: false,
  svgoConfig: {
    plugins: [
      {
        name: 'preset-default',
        params: { overrides: { removeViewBox: false } },
      },
      // Inline SVG in HTML needs no namespace.
      'removeXMLNS',
    ],
  },
  template: ({ imports, interfaces, componentName, props, jsx }, { tpl }) => {
    const name = toIconName(componentName)
    return tpl`
${imports};
${interfaces};

export const ${name} = (${props}) => (
  ${jsx}
);
`
  },
  indexTemplate: (files) =>
    [
      '// Generated by `pnpm icons` from src/shared/assets/icons. Do not edit.',
      ...files.map(({ path: file }) => {
        const name = path.basename(file, path.extname(file))
        return `export { ${name}Icon } from './${name}'`
      }),
    ].join('\n'),
}

export default config
